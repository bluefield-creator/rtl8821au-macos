import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src).read()

header = text[: text.index("*/") + 2]

body = text[text.index("static const u32 rtw8821a_mac[]"):]
body = body[: body.index("static const u8 rtw8821a_pwrtrk_5gb_n")]

exports = []

def decl(m):
    name = m.group(2)
    exports.append(name)
    return ""

body = re.sub(r"RTW_DECL_TABLE_(\w+)\((\w+)(?:,[^)]*)?\);\n", decl, body)
body = body.replace("static const", "const")

with open(out, "w") as f:
    f.write(header + "\n")
    f.write("/* Generated by tools/gen_tables.py from Linux rtw88 rtw8821a_table.c. */\n")
    f.write('#include "rtw_tables.h"\n\n')
    f.write(body)
    for name in exports:
        f.write(f"const unsigned {name}_size = sizeof({name}) / sizeof({name}[0]);\n")

print("exported:", ", ".join(exports + ["card_enable_flow_8821a",
                                        "enter_lps_flow_8821a",
                                        "card_disable_flow_8821a"]))
